// docs/12 on the CLI side: oc-host.jsonc `sandbox`, OC_SETTINGS, the rendered wrangler.jsonc, `ochost sandbox`.
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import type { AccessHooks } from "../src/access.ts";
import { defaultConfigText, parseJsonc, validateConfig, workerSettings } from "../src/config.ts";
import { renderWranglerJsonc } from "../src/deploy.ts";
import { makeCtx } from "../src/ops-lib.ts";
import { sandbox, sandboxFlags, setSandboxKey } from "../src/sandbox.ts";
import { FakeOps, installDir, run, T0 } from "./ops-fake.ts";

const ACCT = "a".repeat(32);
const cfgOf = () =>
  validateConfig(parseJsonc(defaultConfigText({ name: "oc-x", inst: "a1b2c3", accountId: ACCT })));

describe("config", () => {
  it("init writes sandbox off; OC_SETTINGS carries it; a bad value is refused", () => {
    const c = cfgOf();
    expect(c.sandbox).toBe("off");
    expect(workerSettings(c, "https://x").sandbox).toBe("off");
    expect(workerSettings({ ...c, sandbox: undefined }, "https://x").sandbox).toBe("off");
    expect(workerSettings({ ...c, sandbox: "on" }, "https://x").sandbox).toBe("on");
    expect(workerSettings({ ...c, sandbox: "all" }, "https://x").sandbox).toBe("all");
    expect(() => validateConfig({ ...c, sandbox: "yes" })).toThrow(/sandbox must be on, all or off/);
  });

  it("setSandboxKey flips the key in place, keeps comments, inserts when absent", () => {
    const t = defaultConfigText({ name: "oc-x", inst: "a1b2c3", accountId: ACCT });
    const on = setSandboxKey(t, "on");
    expect((parseJsonc(on) as any).sandbox).toBe("on");
    expect(on.split("\n").length).toBe(t.split("\n").length);
    expect(on).toContain("// Generated by ochost init");
    const bare = '{\n  "name": "x" // c\n}\n';
    expect(parseJsonc(setSandboxKey(bare, "on"))).toEqual({ sandbox: "on", name: "x" });
  });

  it("wrangler.jsonc always declares SandboxSession: its own image, durable_object policy, SANDBOX binding", () => {
    const w = parseJsonc(
      renderWranglerJsonc(cfgOf(), { accountId: ACCT, url: "https://x", source: "/src" }),
    ) as any;
    const sb = w.containers.find((c: any) => c.class_name === "SandboxSession");
    expect(sb).toEqual({
      class_name: "SandboxSession",
      scheduling_policy: "durable_object",
      images: { sbx: { dockerfile: "/src/image/sandbox/Dockerfile", build_context: "/src/image/sandbox" } },
    });
    expect(w.durable_objects.bindings).toContainEqual({ name: "SANDBOX", class_name: "SandboxSession" });
    expect(w.exports.SandboxSession).toEqual({ type: "durable-object", storage: "sqlite" });
  });

  it("testTimers: OC_TIMERS on a test install only; bad values refused", () => {
    const c = { ...cfgOf(), testTimers: { l5PendingMs: 600_000 } };
    const vars = (fake: boolean) =>
      (
        parseJsonc(
          renderWranglerJsonc(validateConfig(c), {
            accountId: ACCT,
            url: "https://x",
            source: "/src",
            fakeTelegram: fake,
          }),
        ) as any
      ).vars;
    expect(vars(true).OC_TIMERS).toBe('{"l5PendingMs":600000}');
    expect(vars(false).OC_TIMERS).toBeUndefined();
    expect(vars(true).OC_TEST).toBe("1");
    expect(() => validateConfig({ ...cfgOf(), testTimers: { l5PendingMs: -1 } })).toThrow(/testTimers/);
    expect(() => validateConfig({ ...cfgOf(), testTimers: [1] })).toThrow(/testTimers/);
  });
});

describe("ochost sandbox", () => {
  let f: FakeOps;
  let dir: string;
  beforeEach(async () => {
    f = await new FakeOps().start();
    f.routes.push((r) => {
      if (r.path === "/ops/sandbox" && r.method === "GET")
        return {
          status: 200,
          body: {
            state: "running",
            lastUseAt: T0 - 120_000,
            lastBackupAt: null,
            lastSleep: "idle",
            wakes: 3,
            exec: { used: 1800, limit: 7200, pct: 0.25 },
            sandbox: { used: 6.5, limit: 8, pct: 0.8125 },
          },
        };
      if (r.path === "/ops/sandbox/sleep" && r.method === "POST")
        return { status: 200, body: { slept: true } };
      return undefined;
    });
    dir = installDir(f.url);
  });
  afterEach(() => f.stop());

  it("status shows state and both budgets", async () => {
    const r = await run("sandbox", ["--dir", dir]);
    expect(r.code).toBe(0);
    expect(r.out).toMatch(/state\s+running/);
    expect(r.out).toMatch(/exec\s+1800s of 7200s today \(25%\)/);
    expect(r.out).toMatch(/sandbox\s+6\.50h of 8h today \(81%\)/);
  });

  it("on writes oc-host.jsonc and names the next steps; no request", async () => {
    const r = await run("sandbox", ["on", "--dir", dir]);
    expect(r.code).toBe(0);
    expect((parseJsonc(readFileSync(join(dir, "oc-host.jsonc"), "utf8")) as any).sandbox).toBe("on");
    expect(r.out).toMatch(/next: ochost deploy, then ochost restart/);
    expect(f.calls("GET", "/ops/sandbox")).toHaveLength(0);
  });

  it("on --apply writes the key, then deploys with it, then restarts", async () => {
    const order: string[] = [];
    const hooks: AccessHooks = {
      async deploy(ctx) {
        order.push(
          `deploy:${(parseJsonc(readFileSync(join(ctx.dir, "oc-host.jsonc"), "utf8")) as any).sandbox}`,
        );
      },
      async restart() {
        order.push("restart");
        return "restarted";
      },
    };
    let out = "";
    const ctx = makeCtx(
      ["on", "--apply", "--dir", dir],
      sandboxFlags,
      { env: {} },
      {
        stdout: (t) => {
          out += t;
        },
        stderr: () => {},
      },
    );
    expect(await sandbox(ctx, hooks)).toBe(0);
    expect(order).toEqual(["deploy:on", "restart"]);
    expect(out).toMatch(/deployed; restart: restarted/);
    expect(out).not.toMatch(/next:/);
  });

  it("on --apply: a failed deploy stops before the restart and says the file is changed", async () => {
    const order: string[] = [];
    const hooks: AccessHooks = {
      async deploy() {
        throw new Error("wrangler boom");
      },
      async restart() {
        order.push("restart");
        return "restarted";
      },
    };
    const ctx = makeCtx(
      ["off", "--apply", "--dir", dir],
      sandboxFlags,
      { env: {} },
      {
        stdout: () => {},
        stderr: () => {},
      },
    );
    await expect(sandbox(ctx, hooks)).rejects.toThrow(/deploy failed: wrangler boom/);
    expect(order).toEqual([]);
    expect((parseJsonc(readFileSync(join(dir, "oc-host.jsonc"), "utf8")) as any).sandbox).toBe("off");
  });

  it("sleep posts once", async () => {
    const r = await run("sandbox", ["sleep", "--dir", dir]);
    expect(r.code).toBe(0);
    expect(f.calls("POST", "/ops/sandbox/sleep")).toHaveLength(1);
    expect(r.out).toMatch(/sandbox asleep/);
  });
});
